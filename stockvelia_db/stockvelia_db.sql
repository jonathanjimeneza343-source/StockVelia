-- -----------------------------------------------------------------------------
-- 1. FUNCIONES Y PROCEDIMIENTOS
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.actualizar_stock() 
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    stock_actual INTEGER;
BEGIN
    SELECT stock INTO stock_actual 
    FROM productos 
    WHERE id_producto = NEW.id_producto;

    IF NEW.tipo_movimiento = 'ENTRADA' THEN
        UPDATE productos
        SET stock = stock + NEW.cantidad
        WHERE id_producto = NEW.id_producto;

    ELSIF NEW.tipo_movimiento IN ('SALIDA', 'BAJA') THEN
        IF stock_actual < NEW.cantidad OR stock_actual IS NULL THEN
            RAISE EXCEPTION 'Operación cancelada: Stock insuficiente para procesar la transacción del producto ID %', NEW.id_producto;
        END IF;

        UPDATE productos
        SET stock = stock - NEW.cantidad
        WHERE id_producto = NEW.id_producto;
    END IF;

    RETURN NEW;
END;
$$;

-- -----------------------------------------------------------------------------
-- 2. TABLAS Y SECUENCIAS
-- -----------------------------------------------------------------------------

-- Empresa
CREATE TABLE public.empresa (
    id_empresa INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    correo VARCHAR(150) NOT NULL UNIQUE,
    fecha_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    estado BOOLEAN DEFAULT true
);

-- Categorías
CREATE TABLE public.categorias (
    id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    descripcion TEXT,
    id_empresa INTEGER,
    CONSTRAINT uc_nombre_empresa UNIQUE (nombre, id_empresa)
);

-- Permisos
CREATE TABLE public.permisos (
    id_permiso INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion TEXT
);

-- Roles
CREATE TABLE public.roles (
    id_rol INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL UNIQUE
);

-- Inserción de roles por defecto (Soluciona el error de llave foránea)
INSERT INTO public.roles (nombre) VALUES ('Administrador'), ('Empleado') 
ON CONFLICT (nombre) DO NOTHING;

-- Roles - Permisos (Tabla intermedia)
CREATE TABLE public.roles_permisos (
    id_rol INTEGER NOT NULL,
    id_permiso INTEGER NOT NULL,
    PRIMARY KEY (id_rol, id_permiso)
);

-- Usuarios
CREATE TABLE public.usuario (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa INTEGER NOT NULL,
    id_rol INTEGER NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    correo VARCHAR(150) NOT NULL UNIQUE,
    password TEXT NOT NULL,
    intentos_fallidos INTEGER DEFAULT 0,
    bloqueo_hasta TIMESTAMP,
    estado BOOLEAN DEFAULT true,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Productos
CREATE TABLE public.productos (
    id_producto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa INTEGER NOT NULL,
    id_categoria INTEGER NOT NULL,
    codigo VARCHAR(50) NOT NULL UNIQUE,
    nombre VARCHAR(150) NOT NULL,
    descripcion TEXT,
    precio NUMERIC(12,2) NOT NULL CONSTRAINT productos_precio_check CHECK (precio >= 0),
    stock INTEGER DEFAULT 0 CONSTRAINT productos_stock_check CHECK (stock >= 0),
    stock_minimo INTEGER DEFAULT 5 CONSTRAINT productos_stock_minimo_check CHECK (stock_minimo >= 0),
    estado BOOLEAN DEFAULT true,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    imagen TEXT
);

-- Movimientos de Inventario
CREATE TABLE public.movimientos_inventario (
    id_movimiento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto INTEGER NOT NULL,
    id_usuario INTEGER NOT NULL,
    tipo_movimiento VARCHAR(20) NOT NULL,
    motivo VARCHAR(50) NOT NULL,
    cantidad INTEGER NOT NULL CONSTRAINT movimientos_inventario_cantidad_check CHECK (cantidad > 0),
    observacion TEXT,
    fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Auditoría
CREATE TABLE public.auditoria (
    id_auditoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL,
    tabla_afectada VARCHAR(50),
    accion VARCHAR(20),
    registro_id INTEGER,
    descripcion TEXT,
    fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Códigos de Recuperación
CREATE TABLE public.codigos_recuperacion (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correo VARCHAR(255) NOT NULL,
    codigo VARCHAR(6) NOT NULL,
    expira_en TIMESTAMP NOT NULL
);

-- Blacklist de Tokens
CREATE TABLE public.tokens_blacklist (
    id_token INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token TEXT NOT NULL,
    fecha_expiracion TIMESTAMP NOT NULL,
    fecha_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- -----------------------------------------------------------------------------
-- 3. VISTAS
-- -----------------------------------------------------------------------------
CREATE VIEW public.vista_usuarios AS
SELECT 
    nombre,
    correo,
    CASE
        WHEN id_rol = 1 THEN 'Administrador'
        ELSE 'Empleado'
    END AS rol,
    estado
FROM public.usuario;

-- -----------------------------------------------------------------------------
-- 4. LLAVES FORÁNEAS (FOREIGN KEYS)
-- -----------------------------------------------------------------------------

-- Categorías -> Empresa
ALTER TABLE public.categorias
    ADD CONSTRAINT fk_categorias_empresa FOREIGN KEY (id_empresa) REFERENCES public.empresa(id_empresa) ON DELETE CASCADE;

-- Roles Permisos
ALTER TABLE public.roles_permisos
    ADD CONSTRAINT fk_roles_permisos_permiso FOREIGN KEY (id_permiso) REFERENCES public.permisos(id_permiso),
    ADD CONSTRAINT fk_roles_permisos_rol FOREIGN KEY (id_rol) REFERENCES public.roles(id_rol);

-- Usuarios -> Empresa & Rol
ALTER TABLE public.usuario
    ADD CONSTRAINT fk_empresa FOREIGN KEY (id_empresa) REFERENCES public.empresa(id_empresa),
    ADD CONSTRAINT fk_rol FOREIGN KEY (id_rol) REFERENCES public.roles(id_rol);

-- Productos -> Empresa & Categoría
ALTER TABLE public.productos
    ADD CONSTRAINT fk_empresa_producto FOREIGN KEY (id_empresa) REFERENCES public.empresa(id_empresa),
    ADD CONSTRAINT fk_categoria_producto FOREIGN KEY (id_categoria) REFERENCES public.categorias(id_categoria);

-- Movimientos de Inventario -> Producto & Usuario
ALTER TABLE public.movimientos_inventario
    ADD CONSTRAINT fk_producto_mov FOREIGN KEY (id_producto) REFERENCES public.productos(id_producto),
    ADD CONSTRAINT fk_usuario_mov FOREIGN KEY (id_usuario) REFERENCES public.usuario(id_usuario);

-- Auditoría -> Usuario
ALTER TABLE public.auditoria
    ADD CONSTRAINT fk_usuario_auditoria FOREIGN KEY (id_usuario) REFERENCES public.usuario(id_usuario);

-- -----------------------------------------------------------------------------
-- 5. TRIGGERS
-- -----------------------------------------------------------------------------
CREATE TRIGGER trg_actualizar_stock
    AFTER INSERT ON public.movimientos_inventario
    FOR EACH ROW
    EXECUTE FUNCTION public.actualizar_stock();